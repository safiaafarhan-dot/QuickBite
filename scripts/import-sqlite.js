'use strict';

/**
 * One-way import of an existing SQLite database into PostgreSQL.
 *
 *   node scripts/import-sqlite.js ./data/quickbite.db            # dry run
 *   node scripts/import-sqlite.js ./data/quickbite.db --write    # do it
 *
 * Run it once, against the PostgreSQL database you are about to deploy
 * against, before the app starts taking new orders.
 *
 * ── What it preserves, and the one thing it deliberately does not ──
 *
 * Rows keep their original primary keys, so every foreign key — orders →
 * users, order_items → orders, reviews → users — still points where it did.
 * The identity columns are GENERATED BY DEFAULT precisely so explicit ids can
 * be written here, and every sequence is reset afterwards; skip that and the
 * next real insert would collide with an imported id.
 *
 * The exception is the menu and the coupon catalogue. Those are *reference
 * data*: the application rebuilds them from `server/data/menu.js` on every
 * boot, keyed on the dish name and the coupon code. So this script does not
 * copy those two tables at all. It loads them from the source files, then
 * **remaps every `item_id` by dish name** as it copies the tables that point
 * at them.
 *
 * That remap is the whole reason this script is not a plain row copy. A fresh
 * PostgreSQL menu is numbered in whatever order the seed inserted it, which
 * need not match the ids in a SQLite file written months earlier. Copying
 * `order_items.item_id` verbatim would silently re-point historical orders at
 * the wrong dishes — every figure in the admin dashboard would still add up,
 * and every one of them would be wrong.
 *
 * It is otherwise conservative:
 *
 *   - a dry run by default, printing exactly what it would copy;
 *   - it refuses to import into a table that already holds rows, unless
 *     `--force` is given, so it cannot quietly double an earlier import;
 *   - the whole copy is one transaction, so a failure leaves nothing behind.
 *
 * The SQLite file is only ever opened read-only.
 */

const fs = require('node:fs');
const path = require('node:path');

const { sql, transaction, initDb, closeDb, describeConnection, CONNECTION_HELP } = require('../server/db');

const args = process.argv.slice(2);
const write = args.includes('--write');
const force = args.includes('--force');
const source = args.find((a) => !a.startsWith('--'));

/*
 * Parents before children, so no insert ever references a row that has not
 * arrived yet. `menu_items` and `coupons` are absent on purpose — see above.
 * `schema_migrations` is absent too: this database records its own migration
 * history, and copying the old one would claim migrations ran that never did.
 */
const TABLES = [
  { name: 'users', id: 'id' },
  { name: 'orders', id: 'id' },
  { name: 'order_items', id: 'id', itemRef: 'item_id', itemNullable: true },
  { name: 'order_events', id: 'id' },
  { name: 'cart_items', id: null, itemRef: 'item_id' },
  { name: 'favorites', id: null, itemRef: 'item_id' },
  { name: 'addresses', id: 'id' },
  { name: 'reviews', id: 'id', itemRef: 'item_id' },
  { name: 'coupon_redemptions', id: 'id' },
  { name: 'idempotency_keys', id: null },
  { name: 'payment_events', id: 'id' },
  { name: 'item_events', id: 'id', itemRef: 'item_id' },
];

/** Columns that held a UTC timestamp as text in SQLite. */
const TIMESTAMP_COLUMNS = new Set([
  'created_at', 'updated_at', 'placed_at', 'at', 'redeemed_at', 'expires_at',
]);

function usage(message) {
  console.error(`\n  ✗ ${message}\n`);
  console.error('  Usage: node scripts/import-sqlite.js <path-to.db> [--write] [--force]\n');
  console.error('    --write   actually copy (the default is a dry run)');
  console.error('    --force   allow importing into tables that already hold rows\n');
  process.exit(1);
}

function sqliteTables(db) {
  return new Set(
    db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all().map((r) => r.name)
  );
}

const columnsOf = (db, table) =>
  db.prepare(`PRAGMA table_info(${table})`).all().map((c) => c.name);

/**
 * SQLite stored `'YYYY-MM-DD HH:MM:SS'` with no zone, meaning UTC here. Saying
 * so explicitly stops PostgreSQL reading it as the server's local time and
 * shifting every historical order by the offset.
 */
function coerce(column, value) {
  if (value === null || value === undefined) return null;
  if (TIMESTAMP_COLUMNS.has(column) && typeof value === 'string' && value.length > 0) {
    return /[+-]\d{2}(:?\d{2})?$|Z$/.test(value) ? value : `${value}+00`;
  }
  return typeof value === 'bigint' ? Number(value) : value;
}

async function main() {
  if (!source) usage('No SQLite file given.');
  const file = path.resolve(source);
  if (!fs.existsSync(file)) usage(`No such file: ${file}`);

  if (!process.env.DATABASE_URL) {
    console.error(CONNECTION_HELP);
    process.exit(1);
  }

  let DatabaseSync;
  try {
    ({ DatabaseSync } = require('node:sqlite'));
  } catch {
    usage('This Node build has no node:sqlite, so the old database cannot be read. Node 22.5+ is needed.');
  }

  console.log(`\n  Source : ${file}`);
  console.log(`  Target : ${describeConnection()}`);
  console.log(`  Mode   : ${write ? 'WRITE' : 'dry run (pass --write to copy)'}\n`);

  /*
   * Migrate *and* seed: the menu has to be present and canonical before
   * anything can be remapped onto it.
   */
  await initDb({ log: false, seed: true });

  const db = new DatabaseSync(file, { readOnly: true });
  const present = sqliteTables(db);

  /* ---------------------------------------------------------------- */
  /* Build the dish remap: old id → new id, matched on name            */
  /* ---------------------------------------------------------------- */

  const itemMap = new Map();
  const unmatched = [];

  if (present.has('menu_items')) {
    const oldItems = db.prepare('SELECT id, name FROM menu_items').all();
    const newItems = await sql.all('SELECT id, name FROM menu_items');
    const byName = new Map(newItems.map((r) => [r.name, r.id]));

    for (const row of oldItems) {
      const target = byName.get(row.name);
      if (target === undefined) unmatched.push(row.name);
      else itemMap.set(row.id, target);
    }

    const moved = [...itemMap.entries()].filter(([from, to]) => from !== to).length;
    console.log(`  dish remap: ${itemMap.size} matched by name, ${moved} changed id, ${unmatched.length} not on the current menu`);
    if (unmatched.length > 0) {
      console.log(`              (${unmatched.slice(0, 5).join(', ')}${unmatched.length > 5 ? ', …' : ''})`);
    }
    console.log('');
  }

  /** Translates an old dish id, or null when the dish is gone. */
  const remap = (oldId) => (oldId === null || oldId === undefined ? null : itemMap.get(oldId) ?? null);

  /* ---------------------------------------------------------------- */
  /* Plan                                                              */
  /* ---------------------------------------------------------------- */

  const plan = [];
  let dropped = 0;

  for (const table of TABLES) {
    if (!present.has(table.name)) {
      console.log(`  · ${table.name.padEnd(20)} not in the source file — skipped`);
      continue;
    }

    const rows = db.prepare(`SELECT * FROM ${table.name}`).all();
    const { n: existing } = await sql.get(`SELECT COUNT(*) AS n FROM ${table.name}`);

    if (existing > 0 && !force) {
      console.log(`  ! ${table.name.padEnd(20)} ${String(rows.length).padStart(6)} rows to copy, but the target already holds ${existing}`);
      if (write) {
        console.error(`\n  ✗ Refusing to import into a non-empty ${table.name}.`);
        console.error('    Import into a database that has no QuickBite data yet, or pass --force');
        console.error('    if you genuinely mean to add these rows to what is already there.\n');
        db.close();
        process.exit(1);
      }
      continue;
    }

    /*
     * Rows whose dish is no longer on the menu: an order line can keep its
     * history with a null item_id (the column is nullable for exactly this
     * reason), but a review or a cart line cannot, so those are dropped and
     * counted rather than failing the import.
     */
    let usable = rows;
    if (table.itemRef && !table.itemNullable) {
      usable = rows.filter((r) => remap(r[table.itemRef]) !== null);
      dropped += rows.length - usable.length;
    }

    console.log(`  ${usable.length > 0 ? '✓' : '·'} ${table.name.padEnd(20)} ${String(usable.length).padStart(6)} rows`
      + (usable.length !== rows.length ? `  (${rows.length - usable.length} skipped — dish no longer on the menu)` : ''));

    if (usable.length > 0) plan.push({ table, rows: usable, columns: columnsOf(db, table.name) });
  }

  db.close();

  const total = plan.reduce((n, p) => n + p.rows.length, 0);

  if (!write) {
    console.log(`\n  Dry run only — ${total} rows would be copied${dropped ? `, ${dropped} skipped` : ''}.`);
    console.log('  The menu and coupons are not copied: they are rebuilt from server/data/menu.js');
    console.log('  and every item_id above is remapped onto them by dish name.');
    console.log('\n  Re-run with --write to perform the import.\n');
    return;
  }

  if (total === 0) {
    console.log('\n  Nothing to copy.\n');
    return;
  }

  /*
   * One transaction for the whole import. A failure part-way through — a
   * constraint the old data violates, a dropped connection — leaves the target
   * exactly as it was rather than half-populated.
   */
  await transaction(async (tx) => {
    for (const { table, rows, columns } of plan) {
      // Only columns the PostgreSQL table actually has; an old file may carry
      // a column a later migration removed.
      const targetColumns = (await tx.all(
        `SELECT column_name FROM information_schema.columns
          WHERE table_schema = current_schema() AND table_name = $1`,
        [table.name]
      )).map((r) => r.column_name);

      const shared = columns.filter((c) => targetColumns.includes(c));
      const placeholders = shared.map((_, i) => `$${i + 1}`).join(', ');
      const statement = `INSERT INTO ${table.name} (${shared.join(', ')}) VALUES (${placeholders})`;

      for (const row of rows) {
        const values = shared.map((c) => (
          c === table.itemRef ? remap(row[c]) : coerce(c, row[c])
        ));
        await tx.run(statement, values);
      }

      /*
       * Move the identity sequence past the highest id just imported. Without
       * this the next insert would try to reuse id 1 and fail on the primary
       * key — the most common way a "successful" import turns into a broken
       * application an hour later.
       */
      if (table.id) {
        await tx.run(
          `SELECT setval(
             pg_get_serial_sequence($1, $2),
             GREATEST((SELECT COALESCE(MAX(${table.id}), 0) FROM ${table.name}), 1)
           )`,
          [table.name, table.id]
        );
      }

      console.log(`  → ${table.name.padEnd(20)} ${String(rows.length).padStart(6)} rows copied`);
    }
  });

  console.log(`\n  ✓ Imported ${total} rows${dropped ? `, skipped ${dropped}` : ''}.`);
  console.log('    Check the app, then keep the SQLite file somewhere safe until you are sure.\n');
}

main()
  .then(() => closeDb())
  .catch(async (err) => {
    console.error(`\n  ✗ Import failed: ${err.message}`);
    console.error('    Nothing was committed.\n');
    await closeDb().catch(() => {});
    process.exit(1);
  });
