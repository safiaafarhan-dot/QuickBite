'use strict';

/**
 * Forward-only schema migrations, for PostgreSQL.
 *
 * Each entry runs once, inside a transaction, and is recorded in
 * `schema_migrations`. Migrations must be additive and safe to run against a
 * database that already holds real orders and accounts — never DROP or rewrite
 * a table that holds user data.
 *
 * Two conventions carried over from the SQLite schema on purpose:
 *
 *   Flags stay INTEGER 0/1 rather than becoming BOOLEAN. `is_veg`,
 *   `is_available`, `free_delivery` and the rest are serialised straight into
 *   API responses and compared as numbers by the front end and the tests;
 *   turning them into `true`/`false` would be a breaking API change for no
 *   gain.
 *
 *   Identity columns are GENERATED BY DEFAULT, not ALWAYS, so the SQLite
 *   importer can write rows with their original ids and keep every foreign key
 *   intact. `scripts/import-sqlite.js` resets the sequences afterwards.
 */

/** True when `table` already has a column called `column`. */
async function hasColumn(sql, table, column) {
  const row = await sql.get(
    `SELECT 1 FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name = $1 AND column_name = $2`,
    [table, column]
  );
  return Boolean(row);
}

async function hasTable(sql, table) {
  const row = await sql.get(
    `SELECT 1 FROM information_schema.tables
      WHERE table_schema = current_schema() AND table_name = $1`,
    [table]
  );
  return Boolean(row);
}

/**
 * Adds a column only if it is missing, so re-running is harmless.
 *
 * PostgreSQL has `ADD COLUMN IF NOT EXISTS`, but the explicit check is kept so
 * the helper reads the same as it did under SQLite and so a typo in a table
 * name fails loudly rather than being swallowed.
 */
async function addColumn(sql, table, column, definition) {
  if (!(await hasColumn(sql, table, column))) {
    await sql.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
  }
}

