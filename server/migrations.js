/** Fixed key, so every QuickBite instance contends for the same lock. */
const MIGRATION_LOCK_KEY = 0x51b17e;

const CREATE_LEDGER = `
  CREATE TABLE IF NOT EXISTS schema_migrations (
    name       TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )
`;

/** Names already recorded, or an empty set when the ledger does not exist yet. */
async function appliedNames(sql) {
  if (!(await hasTable(sql, 'schema_migrations'))) return new Set();
  const rows = await sql.all('SELECT name FROM schema_migrations');
  return new Set(rows.map((r) => r.name));
}

/**
 * Applies every migration that has not run yet.
 *
 * Two instances can be migrating at once — a deploy starts the new container
 * while the old one is still serving — so the work is serialised with an
 * advisory lock. Whoever gets it migrates; the other waits, then finds nothing
 * left to do.
 *
 * The lock is `pg_advisory_xact_lock`, taken *inside* the transaction, and that
 * detail is load-bearing rather than stylistic.
 *
 * `pg_advisory_lock` is session-scoped. Through a transaction pooler — which is
 * what Supabase's port 6543 is, and what a free Render service should use — a
 * client connection is not pinned to one server backend between transactions.
 * The lock would be taken on one backend, the migrations would run on another,
 * and the matching unlock would run on a third and return false, stranding the
 * lock on the first backend until its session ended. Every later deploy would
 * then block on a lock nobody holds a handle to any more.
 *
 * A transaction-scoped lock has no such failure mode: PostgreSQL releases it at
 * COMMIT or ROLLBACK, and the whole transaction is guaranteed to stay on one
 * backend even through a pooler.
 *
 * Everything runs in that single transaction, so a failure half way leaves the
 * schema exactly as it was rather than partly migrated.
 *
 * @returns {Promise<string[]>} names of the migrations applied during this call
 */
async function migrate(sql, { log = false } = {}) {
  /*
   * Fast path. A migrated database is the normal case on every cold start, and
   * a free Render instance cold-starts often; this keeps that boot to one
   * cheap read instead of opening a transaction and taking a lock.
   */
  const seen = await appliedNames(sql);
  if (MIGRATIONS.every((m) => seen.has(m.name))) return [];

  const ran = [];

  await sql.run('BEGIN');
  try {
    await sql.run('SELECT pg_advisory_xact_lock($1)', [MIGRATION_LOCK_KEY]);

    // Re-read under the lock: another instance may have applied these while
    // this one waited for it.
    await sql.exec(CREATE_LEDGER);
    const applied = await appliedNames(sql);

    for (const migration of MIGRATIONS) {
      if (applied.has(migration.name)) continue;

      await migration.up(sql);
      await sql.run('INSERT INTO schema_migrations (name) VALUES ($1)', [migration.name]);

      ran.push(migration.name);
      if (log) console.log(`  ↑ ${migration.name}`);
    }

    await sql.run('COMMIT');
    return ran;
  } catch (err) {
    await sql.run('ROLLBACK').catch(() => {});
    throw new Error(`Migration failed: ${err.message}`);
  }
}

